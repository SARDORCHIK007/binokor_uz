def cyrillic(text: str) -> str:
    for latin, cyr in DIGRAPHS:
        text = text.replace(latin, cyr)
    out = []
    for char in text:
        lower = char.lower()
        mapped = LETTERS.get(lower)
        if mapped is None:
            out.append(char)
            continue
        out.append(mapped.upper() if char.isupper() else mapped)
    return "".join(out)


def walk(node: object, fn) -> object:
    if isinstance(node, dict):
        return {key: walk(value, fn) for key, value in node.items()}
    if isinstance(node, str):
        return fn(node)
    return node


